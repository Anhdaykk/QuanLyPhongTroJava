    private void btnCapNhatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCapNhatActionPerformed

    String maPhong = txtMaPhong.getText().trim();
    String tenPhong = txtTenPhong.getText().trim();
    String giaThue = txtGiaThue.getText().trim();
    String dienTich = txtDienTich.getText().trim();
    String trangThai = cboTrangThai.getSelectedItem().toString();

    if (maPhong.isEmpty() || tenPhong.isEmpty()
            || giaThue.isEmpty() || dienTich.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Vui lòng nhập đầy đủ thông tin!");
        return;
    }

    java.math.BigDecimal gia;
    java.math.BigDecimal dienTichSo;

    try {
        gia = new java.math.BigDecimal(giaThue);
        dienTichSo = new java.math.BigDecimal(dienTich);

        if (gia.compareTo(java.math.BigDecimal.ZERO) < 0
                || dienTichSo.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Giá thuê không được âm và diện tích phải lớn hơn 0!");
            return;
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Giá thuê và diện tích phải là số hợp lệ!");
        return;
    }

    String sql = "UPDATE phong_tro SET ma_phong=?, ten_phong=?, "
            + "gia_thue=?, dien_tich=?, trang_thai=? WHERE id_phong=?";

    try (java.sql.Connection conn = KetNoiCSDL.getConnection()) {

        if (conn == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Không kết nối được MySQL!");
            return;
        }

        // Lấy ID phòng từ MySQL bằng mã phòng cũ
        String maPhongCu = model.getValueAt(dong, 1).toString();

        String sqlId = "SELECT id_phong FROM phong_tro WHERE ma_phong=?";

        int idPhong;

        try (java.sql.PreparedStatement pstId =
                conn.prepareStatement(sqlId)) {

            pstId.setString(1, maPhongCu);

            try (java.sql.ResultSet rs = pstId.executeQuery()) {

                if (!rs.next()) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "Không tìm thấy phòng trong MySQL!");
                    return;
                }

                idPhong = rs.getInt("id_phong");
            }
        }

        try (java.sql.PreparedStatement pst =
                conn.prepareStatement(sql)) {

            pst.setString(1, maPhong);
            pst.setString(2, tenPhong);
            pst.setBigDecimal(3, gia);
            pst.setBigDecimal(4, dienTichSo);
            pst.setString(5, trangThai);
            pst.setInt(6, idPhong);

            int ketQua = pst.executeUpdate();

            if (ketQua > 0) {

                model.setValueAt(maPhong, dong, 1);
                model.setValueAt(tenPhong, dong, 2);
                model.setValueAt(gia, dong, 3);
                model.setValueAt(dienTichSo, dong, 4);
                model.setValueAt(trangThai, dong, 5);

                javax.swing.JOptionPane.showMessageDialog(this,
                        "Cập nhật phòng thành công!");

                this.dispose();

            } else {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Không có dữ liệu nào được cập nhật!");
            }
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Lỗi cập nhật phòng: " + e.getMessage());
    }


    }//GEN-LAST:event_btnCapNhatActionPerformed

