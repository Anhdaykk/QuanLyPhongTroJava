    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed

    String maPhong = abc.getText().trim();
    String tenPhong = acc.getText().trim();
    String giaThue = axx.getText().trim();
    String dienTich = ass.getText().trim();
    String trangThai = assi.getSelectedItem().toString();

    if (maPhong.isEmpty() || tenPhong.isEmpty()
            || giaThue.isEmpty() || dienTich.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Vui lòng nhập đầy đủ thông tin!");
        return;
    }

    if (model == null) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Không tìm thấy bảng danh sách phòng!");
        return;
    }

    java.math.BigDecimal gia;
    java.math.BigDecimal dienTichSo;

    try {
        gia = new java.math.BigDecimal(giaThue);
        dienTichSo = new java.math.BigDecimal(dienTich);

        if (gia.compareTo(java.math.BigDecimal.ZERO) < 0
                || dienTichSo.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Giá thuê không được âm và diện tích phải lớn hơn 0!");
            return;
        }

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Giá thuê và diện tích phải là số hợp lệ!");
        return;
    }

    String sql = "INSERT INTO phong_tro "
            + "(ma_phong, ten_phong, gia_thue, dien_tich, trang_thai) "
            + "VALUES (?, ?, ?, ?, ?)";

    try (java.sql.Connection conn = KetNoiCSDL.getConnection()) {

        if (conn == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Không kết nối được MySQL!");
            return;
        }

        try (java.sql.PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, maPhong);
            pst.setString(2, tenPhong);
            pst.setBigDecimal(3, gia);
            pst.setBigDecimal(4, dienTichSo);
            pst.setString(5, trangThai);

            pst.executeUpdate();
        }

        // Chỉ cập nhật bảng giao diện sau khi lưu MySQL thành công
        model.addRow(new Object[]{
            model.getRowCount() + 1,
            maPhong,
            tenPhong,
            gia,
            dienTichSo,
            trangThai,
            "..."
        });

        javax.swing.JOptionPane.showMessageDialog(this,
                "Thêm phòng và lưu vào MySQL thành công!");

        this.dispose();

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Lỗi lưu phòng: " + e.getMessage());
    } 
    }//GEN-LAST:event_btnLuuActionPerformed

