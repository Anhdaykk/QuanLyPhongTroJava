    private void btnCapNhatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCapNhatActionPerformed

    String maKhach = txtMaKhach.getText().trim();
    String hoTen = txtHoTen.getText().trim();
    String sdt = txtSoDienThoai.getText().trim();
    String cccd = txtCCCD.getText().trim();

if (hoTen.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Vui lòng nhập họ tên!");
    return;
}

String sql = "UPDATE khach_thue SET ho_ten=?, "
        + "so_dien_thoai=?, cccd=? WHERE ma_khach=?";

try {
    java.sql.Connection conn = KetNoiCSDL.getConnection();
    java.sql.PreparedStatement ps = conn.prepareStatement(sql);

    ps.setString(1, hoTen);
    ps.setString(2, sdt.isEmpty() ? null : sdt);
    ps.setString(3, cccd.isEmpty() ? null : cccd);
    ps.setString(4, maKhach);

    int ketQua = ps.executeUpdate();

    ps.close();
    conn.close();

    if (ketQua > 0) {
        model.setValueAt(hoTen, dong, 2);
        model.setValueAt(sdt, dong, 3);
        model.setValueAt(cccd, dong, 4);

        javax.swing.JOptionPane.showMessageDialog(this,
                "Cập nhật khách thuê thành công!");

        this.dispose();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Không tìm thấy khách thuê trong MySQL!");
    }

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Lỗi cập nhật: " + e.getMessage());
}

    }//GEN-LAST:event_btnCapNhatActionPerformed

