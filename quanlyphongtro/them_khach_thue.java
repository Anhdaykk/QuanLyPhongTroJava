    private void btnLuuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLuuActionPerformed

    String maKhach = txtMaKhach.getText().trim();
    String hoTen = txtHoTen.getText().trim();
    String sdt = txtSoDienThoai.getText().trim();
    String cccd = txtCCCD.getText().trim();

if (maKhach.isEmpty() || hoTen.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Vui lòng nhập mã khách và họ tên!");
    return;
}

if (model == null) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Không tìm thấy bảng dữ liệu!");
    return;
}

String sql = "INSERT INTO khach_thue "
        + "(ma_khach, ho_ten, so_dien_thoai, cccd) "
        + "VALUES (?, ?, ?, ?)";

try {
    java.sql.Connection conn = KetNoiCSDL.getConnection();
    java.sql.PreparedStatement ps = conn.prepareStatement(sql);

    ps.setString(1, maKhach);
    ps.setString(2, hoTen);
    ps.setString(3, sdt.isEmpty() ? null : sdt);
    ps.setString(4, cccd.isEmpty() ? null : cccd);

    ps.executeUpdate();

    ps.close();
    conn.close();

    javax.swing.JOptionPane.showMessageDialog(this,
            "Thêm khách thuê thành công!");

    this.dispose();

} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this,
            "Lỗi thêm khách thuê: " + e.getMessage());
}

    }//GEN-LAST:event_btnLuuActionPerformed

